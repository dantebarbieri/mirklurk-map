// Regenerates src/itemdata.ts from a decompiled copy of the game's code (UndertaleModTool's CodeEntries folder).
//
//   deno run -R -W --allow-run tools/itemdata.ts "<CodeEntries dir>"
//
// Reads global.itemDB (gml_Object_databank_Alarm_1) and the item and inventory constructors (gml_GlobalScript_scr_items). Only
// numbers the save editor needs to add items the way the game does are copied: sizes, stack limits, durability and container grids.

const [dir] = Deno.args;
if (!dir) {
  console.error('usage: deno run -R -W --allow-run tools/itemdata.ts "<CodeEntries dir>"');
  Deno.exit(2);
}

const databank = Deno.readTextFileSync(`${dir}/gml_Object_databank_Alarm_1.gml`);
const items = Deno.readTextFileSync(`${dir}/gml_GlobalScript_scr_items.gml`);
const enumValue = (text: string) => {
  const m = /^UnknownEnum\.Value_(m?)(\d+)$/.exec(text.trim());
  if (!m) throw new Error(`Not an enum value: ${text}`);
  return (m[1] ? -1 : 1) * Number(m[2]);
};

interface Entry {
  w: number;
  h: number;
  stack: number;
  durability?: number;
  type: number;
  unlootable?: true;
  bag?: [number, number];
  burn?: number;
}
const table = new Map<number, Entry>();

// Each entry: ds_map_set(global.itemDB, UnknownEnum.Value_N, \n{ ...top-level keys at four spaces... });
for (const m of databank.matchAll(/ds_map_set\(global\.itemDB, (UnknownEnum\.Value_m?\d+), \r?\n\{\r?\n([\s\S]*?)\r?\n\}\);/g)) {
  const index = enumValue(m[1]);
  const keys = new Map<string, string>();
  for (const line of m[2].split(/\r?\n/)) {
    const kv = /^ {4}(\w+): (.*?),?$/.exec(line);
    if (kv) keys.set(kv[1], kv[2]);
  }
  // The databank sizes items by their inventory sprite: width and height are its pixels div 16.
  const sprite = /^spr_ui_items(\d+)x(\d+)$/.exec(keys.get("sprite") ?? "");
  const stack = Number(keys.get("stackLimit"));
  if (!Number.isInteger(stack) || !keys.has("type")) throw new Error(`Item ${index} lacks stackLimit or type`);
  const entry: Entry = {
    w: sprite ? Number(sprite[1]) / 16 : 1,
    h: sprite ? Number(sprite[2]) / 16 : 1,
    stack,
    type: enumValue(keys.get("type")!),
  };
  if (keys.has("durabilityMax")) entry.durability = Number(keys.get("durabilityMax"));
  if (keys.get("NONLOOTABLE") === "true" || !sprite) entry.unlootable = true;
  if (keys.has("burnTime")) entry.burn = Number(keys.get("burnTime"));
  table.set(index, entry);
}

// `item(index)` gives these items an empty inventory(width, height) as their first subPart.
const constructor = /function item\(arg0[\s\S]*?\r?\n\}\r?\n/.exec(items)?.[0];
if (!constructor) throw new Error("item constructor not found");
for (
  const m of constructor.matchAll(
    /if \(((?:arg0 == UnknownEnum\.Value_\d+(?: \|\| )?)+)\)\s*\{\s*array_push\(subParts, new inventory\((\d+), (\d+), arg0\)\);/g,
  )
) {
  for (const v of m[1].matchAll(/UnknownEnum\.Value_\d+/g)) {
    const entry = table.get(enumValue(v[0]));
    if (entry) entry.bag = [Number(m[2]), Number(m[3])];
  }
}

// Only torches and lanterns (item_is_lightsource) get burnTimeLeft and lit; other burnTime values are fuel.
const lights = new Set<number>();
for (const name of ["item_is_torch", "item_is_lantern"]) {
  const body = new RegExp(`function ${name}\\(arg0\\)[\\s\\S]*?\\r?\\n\\}`).exec(items)?.[0] ?? "";
  for (const v of body.matchAll(/UnknownEnum\.Value_\d+/g)) lights.add(enumValue(v[0]));
}
if (!lights.size) throw new Error("light sources not found");
for (const [index, entry] of table) if (!lights.has(index)) delete entry.burn;

const sorted = [...table].sort(([a], [b]) => a - b);
const out = `// Generated by tools/itemdata.ts from Mirklurk 0.8.1.5's item database (gml_Object_databank_Alarm_1) and item constructor
// (gml_GlobalScript_scr_items). Do not edit by hand; rerun the tool after a game update.

export interface ItemData {
  /** Cells it covers in a container when not turned sideways: its inventory sprite's size div 16. */
  w: number;
  h: number;
  /** stackLimit: most of it one cell holds. */
  stack: number;
  /** durabilityMax: a new one starts with this; without it, durability is 1. */
  durability?: number;
  /** itemDB type, the equipment category. */
  type: number;
  /** NONLOOTABLE (fists and other built-in weapons): never an item you can carry. */
  unlootable?: true;
  /** Containers: the [width, height] of the empty inventory a new one has. */
  bag?: [number, number];
  /** Torches and lanterns: burnTime, which a new one has left (burnTimeLeft). */
  burn?: number;
}

export const ITEMS: Record<number, ItemData> = {
${sorted.map(([i, e]) => `  ${i}: ${JSON.stringify(e).replace(/"(\w+)":/g, "$1: ")},`).join("\n")}
};
`;

const target = new URL("../src/itemdata.ts", import.meta.url);
Deno.writeTextFileSync(target, out);
const path = decodeURIComponent(target.pathname).replace(/^\/([A-Za-z]:)/, "$1");
await new Deno.Command(Deno.execPath(), { args: ["fmt", "--quiet", path] }).output();
console.log(`src/itemdata.ts: ${table.size} items, ${sorted.filter(([, e]) => e.bag).length} containers, ${lights.size} light sources`);
